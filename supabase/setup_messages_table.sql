-- Create the messages table if it doesn't exist
CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  project_type TEXT,
  message TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS and allow anonymous inserts
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- Note: In a production environment, you might want more restrictive policies.
-- For a public contact form, we allow anyone to insert messages.
CREATE POLICY "Allow public insert" ON messages 
FOR INSERT 
WITH CHECK (true);

-- Optional: Allow authenticated users (like an admin) to read the messages
CREATE POLICY "Allow authenticated read" ON messages
FOR SELECT
USING (auth.role() = 'authenticated');
